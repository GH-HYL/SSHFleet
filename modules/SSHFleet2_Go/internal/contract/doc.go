// Package contract 是契约包：只放站与站之间递的那几张纸的类型与常量，一个函数都不许有。
//
// 现在落的是三张纸（解析交闸门、执行交结算、结算交报告）、两个失败类型、几样内置常量。
// 三张纸的格子按建站 04 的 01 号工单铺满命令模式那一支；其余四份载荷的附加格随阶段 05 加类型。
//
// **这里一个字都装不了**：要说给使用者的话由 `message.Line` 造（字段不导出），契约里
// 只装「哪一类话 + 那句话要填的事实」（见 `Notice`）。谁都能拼一句字塞给屏幕，正是这次
// 重构要去掉的那种口子（ADR-0032 第四条）。
//
// **纸面白名单（ADR-0044）**——裸 `string` 的格子只许装三类东西：
//   - **事实**：数、布尔、枚举名、路径、IP、使用者敲的原值；系统或解析器给的原话也原样带；
//   - **类别常量**：格子里装的是某个类别常量的名字（`CannotStartReason.Head`、`Step.Name`），
//     不是一句拼好的话；
//   - **配置原文**：配置里抄上来的原值（解释器、环境变量、判据表那几张）。
//
// **报文原文只此三格**：`NodeResult.ErrorText`、`NodeResult.Output`、`AnswerResult.AbortLine`。
// 那是远端给的原话，工具不拼也不裁，搬了就是改行为；别处装原话一律按事实登记。
//
// 名单本体住 `internal/guard/paper.go` 的 `paperFields`，一格一行、每行写明是哪一类；契约里
// 多一格裸 `string` 而名单上没有，`go test` 就红。加一格要动检查器代码，diff 里看得见。
//
// 判据见 ADR-0032 第二条；格子清单见 ADR-0035 决定一与上一张图 15 号工单。
