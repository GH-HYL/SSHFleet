package contract

// Landings 是执行站的两个落点：终端输出写到哪儿、执行期日志写到哪儿。
//
// 按位置传两个同型字符串，写反了编译器一句话不说——终端那一路会被写进执行日志，
// 而日志里那句话指着一份不存在的「完整内容」。字段各有名字之后，那个错法写不出来。
//
// **只拦位置写反。** 两格都是裸 string，把执行日志的路径填进 Terminal 照样编译过；
// 这一类只剩人读调用点那一行与两条钉入口的红线兜着，不归类型管（ADR-0060「理由」「代价」）。
//
// **只装执行站用得着的两格。** 归档那边有一整组落点（目录、终端、执行日志、备份……），
// 报告站收的是整组；执行站只写这两份，多给一格就是让它碰上不该碰的东西
// （ADR-0035 决定三：只装下一站要用的）。
type Landings struct {
	Terminal string // 边跑边写的终端输出
	ExecLog  string // 执行期日志
}
