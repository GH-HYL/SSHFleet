package contract

// Resources 是「执行资源」那一格：这次用到的原料在哪。
//
// 两个读者，各取所需：
//   - 执行站拿它去跑（脚本正文、代填文件）；
//   - 报告站收尾时用——`report.txt` 第一段要印「节点清单：…」，备份原料时也要这几条路径。
//
// 本阶段只落清单一条：脚本与代填随阶段 05 加字段。加字段是加格，不是改结构。
type Resources struct {
	// Manifest 是 `-f` 的**原值**：一份清单文件的路径，或那条内联记录
	// （`-f 1.2.3.4,22,root,pw`）。两种形态共用一个字段——它是「使用者写了什么」，
	// 不是「它是不是文件」；分不分得清归解析站，判出来也不往纸上传。
	//
	// 报告站印「节点清单：」时用它，**印之前要遮**（内联记录里带密码）。
	Manifest string
}
